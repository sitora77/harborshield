def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--training-samples", type=int, default=1000)
    parser.add_argument("--evaluation-samples", type=int, default=10000)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "reports")
    args = parser.parse_args()
    bundle = generate(args.training_samples, args.evaluation_samples)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "experiments.json").write_text(json.dumps(bundle, indent=2) + "\n", encoding="utf-8")
    (args.output_dir / "EXPERIMENT_REPORT.md").write_text(markdown_report(bundle), encoding="utf-8")
    if args.output_dir.resolve() == (ROOT / "reports").resolve():
        (ROOT / "docs/EXPERIMENT_REPORT.md").write_text(markdown_report(bundle), encoding="utf-8")
    (args.output_dir / "experiment.html").write_text(render_html(bundle), encoding="utf-8")
    with (args.output_dir / "policy_comparison.csv").open("w", newline="", encoding="utf-8") as file:
        fields = ["scenario", "policy", "counts", "mean_cost", "mean_ci95_low", "mean_ci95_high", "cvar95_cost", "average_transit_days", "carbon_kg"]
        writer = csv.DictWriter(file, fieldnames=fields)
        writer.writeheader()
        for study in bundle["studies"]:
            for row in study["comparison"]:
                writer.writerow({key: study["scenario"] if key == "scenario" else row[key] for key in fields})
    print(f"Generated {len(bundle['studies'])} regime studies, dependence sensitivity and sample-size diagnostic in {args.output_dir}")


if __name__ == "__main__":
    main()
